def state(bases: list) -> str:
    """Runner state key ('1_3' etc.) from a three-base list (None = empty)."""
    return "".join(str(i + 1) if r is not None else "_" for i, r in enumerate(bases))


def index(inning: int, half: str, home_lead: int, bases: list, outs: int) -> float:
    """Leverage of the coming plate appearance; `home_lead` is home runs minus away."""
    row = table()[(min(inning, 9), half)][min(outs, 2)][STATES.index(state(bases))]
    top = len(row) - 5  # highest margin the row covers: 0 or +4
    margin = max(-4, min(top, home_lead))
    value = row[margin + 4]
    extra = abs(home_lead) - 4
    if extra > 0:
        value *= 0.5**extra
    return value
